//! Routing and handler registration for incoming RPC calls.

use std::{collections::HashMap, sync::Arc};
use tokio::io::{AsyncRead, AsyncWrite};

use crate::{
    Value,
    rpc::{RpcContext, RpcDispatcher, RpcError, RpcPeer, RpcResult},
};

/// A method implementation on the receiving peer.
///
/// `context` can initiate reverse calls on the *same connection*.
/// It is intentionally weak; storing it does not retain a connection.
#[async_trait::async_trait]
pub trait RpcHandler<S>: Send + Sync {
    /// The name of the method to handle. Must be unique within a router.
    fn name(&self) -> &'static str;

    /// Handle a request. `state` is the application state and `params`
    /// are the serialized positional arguments.
    async fn handle(&self, context: &RpcContext, state: &S, params: &Value) -> RpcResult;
}

/// Routes incoming methods to their registered implementations.
pub struct RpcRouter<S> {
    handlers: HashMap<String, Box<dyn RpcHandler<S>>>,
}

impl<S> Default for RpcRouter<S> {
    fn default() -> Self {
        Self::new()
    }
}

impl<S> RpcRouter<S> {
    /// Create a new router with no registered handlers.
    pub fn new() -> Self {
        Self {
            handlers: HashMap::new(),
        }
    }

    /// Replaces a handler with the same name, returning the old handler.
    pub fn register<H>(&mut self, handler: H) -> Option<Box<dyn RpcHandler<S>>>
    where
        H: RpcHandler<S> + 'static,
    {
        self.handlers
            .insert(handler.name().to_owned(), Box::new(handler))
    }

    /// Fluent registration. Accepts the registration *function* generated by
    /// `#[rpc]`, e.g. `.route(echo::register)`.
    ///
    /// The generated registration function includes all method aliases.
    pub fn route<F>(mut self, register: F) -> Self
    where
        F: FnOnce(&mut Self),
    {
        register(&mut self);
        self
    }

    /// Check if a method is registered.
    pub fn contains(&self, method: &str) -> bool {
        self.handlers.contains_key(method)
    }
}

impl<S: Sync> RpcRouter<S> {
    /// Dispatch an incoming request to the appropriate handler.
    pub async fn dispatch(
        &self,
        context: &RpcContext,
        state: &S,
        method: &str,
        params: &Value,
    ) -> RpcResult {
        let handler = self
            .handlers
            .get(method)
            .ok_or_else(|| RpcError::method_not_found(method))?;
        handler.handle(context, state, params).await
    }
}

/// Adapts a typed router and its state to the type-erased dispatcher.
pub struct RoutedDispatcher<S> {
    state: Arc<S>,
    router: Arc<RpcRouter<S>>,
}

impl<S> RoutedDispatcher<S> {
    /// Create a new dispatcher with the given state and router.
    pub fn new(state: S, router: RpcRouter<S>) -> Self {
        Self::from_shared(Arc::new(state), Arc::new(router))
    }

    /// Create a new dispatcher with the given state and router, both wrapped in `Arc`.
    pub fn from_shared(state: Arc<S>, router: Arc<RpcRouter<S>>) -> Self {
        Self { state, router }
    }
}

#[async_trait::async_trait]
impl<S> RpcDispatcher for RoutedDispatcher<S>
where
    S: Send + Sync + 'static,
{
    async fn dispatch(&self, context: &RpcContext, method: &str, params: &Value) -> RpcResult {
        self.router
            .dispatch(context, self.state.as_ref(), method, params)
            .await
    }
}

// Keep the transport bidirectional; this constructor merely attaches routes.
// The implementation lives here so peer.rs itself stays unchanged.
impl RpcPeer {
    /// Start a bidirectional peer with an incoming RPC router.
    pub fn from_stream_with_router<T, S>(stream: T, state: S, router: RpcRouter<S>) -> Self
    where
        T: AsyncRead + AsyncWrite + Unpin + Send + 'static,
        S: Send + Sync + 'static,
    {
        Self::from_stream_with_dispatcher(stream, Arc::new(RoutedDispatcher::new(state, router)))
    }
}
